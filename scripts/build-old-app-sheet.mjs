// Regenerates old-app/api/sheet.js (the drop-in for the old app's Vercel project) from lib/ops.js + api/sheet.js.
//   node scripts/build-old-app-sheet.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const ops = readFileSync('lib/ops.js', 'utf8').split("import { createClient } from '@supabase/supabase-js';")[1]
  .replace(/^export (const|function|async function) /gm, '$1 ');
const head = `// /api/sheet for the OLD app (at-dev-tracker) — session 7b. Self-contained copy of lib/ops.js + api/sheet.js from
// RM-AT-Developer so both apps read and write the same Postgres store. Generated by scripts/build-old-app-sheet.mjs;
// edit the source files there, not this one. Requires \`@supabase/supabase-js\` in the old app's package.json and the
// env vars SUPABASE_URL / SUPABASE_SERVICE_KEY (and optionally RESEND_API_KEY / RESEND_FROM) in its Vercel project.
import { createClient } from '@supabase/supabase-js';
`;
const tail = readFileSync('old-app/api/sheet.js', 'utf8').split('export const config')[1];
mkdirSync('old-app/api', { recursive: true });
writeFileSync('old-app/api/sheet.js', head + ops + '\nexport const config' + tail);
console.log('old-app/api/sheet.js regenerated');
